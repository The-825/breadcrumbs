'use strict';
const assert=require('node:assert/strict');
const {Workflow}=require('./core.js');
const w=new Workflow();
const v={request:'Synthetic revision',owner:'Review role',due:''};
w.intake('SYN-201',v);assert.equal(w.records[0].state,'held');
assert.throws(()=>w.resolve('SYN-201',{...v,due:'2026-11-01'},{},''),/what changed/);
assert.equal(w.records[0].values.due,'');
w.resolve('SYN-201',{...v,due:'2026-11-01'},{},'Fictional requester supplied a date.');
w.act('SYN-201','schedule');w.act('SYN-201','complete','Local synthetic result');
assert.equal(w.records[0].state,'done');
assert.equal(JSON.parse(w.history.find(e=>e.type==='review_resolved').detail).previous.values.due,'');
w.intake('SYN-202',{...v,due:'2026-11-01'},{conflict:true});
assert.throws(()=>w.prepareDraft('SYN-202'),/conflicting/);
w.resolve('SYN-202',{...v,request:'One clarified instruction',due:'2026-11-01'},{},'Fictional requester chose one instruction.');
w.prepareDraft('SYN-202');assert.match(w.records[1].draft,/UNSENT/);
w.intake('SYN-203',{...v,due:'2026-11-01'},{externalAction:true});w.prepareDraft('SYN-203');
w.resolve('SYN-203',{...v,request:'Changed synthetic text',due:'2026-11-01'},{externalAction:true},'Corrected draft input; permission still missing.');
assert.equal(w.records[2].draft,'');assert.equal(w.records[2].state,'held');
w.intake('SYN-204',{...v,due:'2026-11-01'},{preparedFollowUp:true,ackMissing:true});
assert.throws(()=>w.resolve('SYN-204',{...v,due:'2026-11-01'},{},'Attempt to clear unknown without evidence.'),/evidence reference/);
assert.equal(w.records[3].delivery.acknowledged,'unknown');
w.resolve('SYN-204',{...v,due:'2026-11-01'},{},'Fictional acknowledgment supplied.','SYN-EVIDENCE-001');
assert.equal(w.records[3].delivery.acknowledged,'synthetic_evidence_recorded');assert.equal(w.records[3].delivery.sent,'not_connected');
w.intake('SYN-205',{...v,due:'2026-11-01'},{externalAction:true});
w.resolve('SYN-205',{...v,due:'2026-11-01'},{externalAction:true,preparedFollowUp:true,ackMissing:true},'Discovered a prior prepared follow-up with unknown acknowledgment.');
const changed=w.records.find(r=>r.id==='SYN-205');
assert.equal(changed.delivery.prepared,true);assert.equal(changed.delivery.acknowledged,'unknown');assert(changed.holds.includes('missing_delivery_acknowledgment'));
assert.throws(()=>w.prepareDraft('SYN-205'),/Missing acknowledgment/);
assert.throws(()=>w.resolve('SYN-205',{...v,due:'2026-11-01'},{externalAction:true},'Attempt to remove newly asserted uncertainty.'),/evidence reference/);
assert.equal(changed.delivery.acknowledged,'unknown');
w.resolve('SYN-205',{...v,due:'2026-11-01'},{externalAction:true},'Invented acknowledgment reference supplied.','SYN-EVIDENCE-205');
assert.equal(changed.delivery.acknowledged,'synthetic_evidence_recorded');assert.deepEqual(changed.holds,['missing_permission']);assert.equal(changed.delivery.sent,'not_connected');
console.log('PASS: held resolve/resume; conflict draft block; stale draft invalidation; acknowledgment evidence guard including newly asserted uncertainty; no connected delivery.');
