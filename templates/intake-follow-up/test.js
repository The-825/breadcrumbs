'use strict';
const assert=require('node:assert/strict');
const {Workflow}=require('./core.js');
const w=new Workflow();
const v={request:'Synthetic draft',owner:'Reviewer',due:'2026-11-01'};
assert.throws(()=>w.intake('SYN-001',{request:'Incomplete'}),/Missing/);
assert.equal(w.records.length,0);
w.intake('SYN-001',v);w.intake('SYN-001',v);
assert.equal(w.records.length,1);
assert.throws(()=>w.intake('SYN-001',{...v,owner:'Changed'}),/different input/);
w.act('SYN-001','schedule','',true);
assert.equal(w.records[0].state,'new');
w.act('SYN-001','schedule');
assert.throws(()=>w.act('SYN-001','complete',''),/outcome/);
w.act('SYN-001','complete','Synthetic draft accepted',true);
assert.equal(w.records[0].state,'follow_up');
w.act('SYN-001','complete','Synthetic draft accepted');
assert.equal(w.records[0].state,'done');
assert.throws(()=>w.act('SYN-001','complete','Again'),/current state/);
assert.deepEqual(w.history.map(e=>e.type),['intake','duplicate_ignored','action_failed','schedule','action_failed','complete']);
const custom=new Workflow([{key:'item',label:'Sample item',required:true}]);
custom.intake('SYN-CUSTOM',{item:'=SUM(1,2)'});
assert.match(custom.csv(),/'=SUM/);
assert.throws(()=>new Workflow([{key:'constructor',label:'Bad',required:true}]),/Invalid/);
const copy=w.snapshot();copy.records[0].state='new';assert.equal(w.records[0].state,'done');
console.log('PASS: missing input, idempotent intake, conflict, failed schedule/completion recovery, outcome gate, invalid transition, history, custom fields, CSV formula escaping, snapshot isolation.');
if(process.argv.includes('--receipt'))require('node:fs').writeFileSync('synthetic-walkthrough.json',JSON.stringify(w.snapshot(),null,2));
